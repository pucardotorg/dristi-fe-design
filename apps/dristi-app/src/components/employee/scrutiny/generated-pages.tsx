const PARA = "mt-3";
const FOOT = "mt-6 text-center text-caption text-paper-muted-foreground";

function Synopsis() {
  const courtText = useCourtText();
  return (
    <div className={PAGE}>
      <h4 className={HEADING}>{courtText("IN THE 24×7 ON COURT AT AHMEDABAD")}</h4>
      <div className={SUB}>
        {/* No number before scrutiny: none is allotted until registration. */}
        Under Section 138, Negotiable Instruments Act, 1881
        <br />
        Prateek Agrawal (Complainant) v. Deepak Choudhary (Accused)
      </div>
      <h4 className={cn(HEADING, "mt-1.5")}>SYNOPSIS</h4>
      <div className={PARA}>
        1. The accused issued cheque no. 230270 dated 05/04/2019 drawn on State Bank
        of India for ₹52,05,000 towards discharge of a legally enforceable debt.
      </div>
      <div className={PARA}>
        2. On presentation, the cheque was returned unpaid with the endorsement
        &ldquo;funds insufficient&rdquo; vide return memo dated 04/04/2016.
      </div>
      <div className={PARA}>
        3. A legal demand notice dated 12/04/2016 was dispatched by registered post;
        despite service, no payment was received within the statutory period.
      </div>
      <div className={PARA}>
        4. The complainant therefore prays that cognizance be taken and the accused be
        tried and punished under Section 138 of the Act.
      </div>
      <div className={FOOT}>
        {courtText("Generated by ON Courts")} from the filed fields · Doc 1 of 7
      </div>
    </div>
  );
}

